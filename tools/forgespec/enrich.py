#!/usr/bin/env python3
"""Merge events.generated.json (bytecode scan) with hooks-index.json (patch scan) and the curated notes in
curated_events.py into docs/forge-spec/events.json and events.md.

usage: enrich.py <events.generated.json> <hooks-index.json> <outDir>
"""
import json, os, sys, re
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from curated_events import CURATED, SERVER_ONLY_CLASSES, CLIENT_PKGS

gen = json.load(open(sys.argv[1]))
hooks = json.load(open(sys.argv[2]))
out = sys.argv[3]


def simple(c):
    return c.split("/")[-1]


def dotted_forge(c):  # net/minecraftforge/client/event/GuiOpenEvent -> client.event.GuiOpenEvent
    return c.replace("net/minecraftforge/", "").replace("/", ".").replace("$", ".")


def refs_for(ev, site):
    res, seen = [], set()
    owner = simple(site["class"]).split("$")[0]
    want = owner + "." + site["method"]
    newsym = "new " + dotted_forge(ev["event"])

    def scan(cls, sym):
        h = hooks.get(cls)
        if not h:
            return
        for it in h["hooks"]:
            if sym in it["symbols"]:
                key = (h["patch"], it["patchLine"])
                if key not in seen:
                    seen.add(key)
                    res.append({"patch": h["patch"], "patchLine": it["patchLine"], "hunk": it["hunk"]})

    if site["kind"] == "patched-vanilla":
        scan(site["class"].split("$")[0], newsym)
        scan(site["class"], newsym)
    else:
        for vc in site["vanillaCallers"]:
            scan(vc["class"].split("$")[0], want)
        if not res:
            for cls in hooks:
                scan(cls, want)
    return res[:6]


def classify(ev):
    n = ev["event"]
    cur = CURATED.get(n, {})
    if "side" in cur:
        return cur["side"]
    if any(n.startswith(p) for p in CLIENT_PKGS):
        return "CLIENT"
    callers = {c["class"].split("$")[0] for s in ev["sites"] for c in s["vanillaCallers"]}
    if "terraingen" in n or "fml/common/network/FMLNetworkEvent$Server" in n:
        return "SERVER"
    if not callers:
        return "UNKNOWN"
    if all("/client/" in c for c in callers):
        return "CLIENT"
    if all(c in SERVER_ONLY_CLASSES or "/server/" in c for c in callers):
        return "SERVER"
    return "BOTH"


rows = []
for ev in gen:
    for s in ev["sites"]:
        s["patchRefs"] = refs_for(ev, s)
    cur = CURATED.get(ev["event"], {})
    side = classify(ev)
    mp = cur.get("mp") or {"CLIENT": "yes", "BOTH": "yes", "SERVER": "no", "UNKNOWN": "check"}[side]
    ev["side"] = side
    ev["mpClient"] = mp
    ev["bus"] = sorted({s["bus"].rstrip("?") for s in ev["sites"] if s["bus"].rstrip("?") != "?"}) or cur.get("bus", [])
    for k in ("thread", "when", "ordering", "notes", "phase"):
        if k in cur:
            ev[k] = cur[k]
    rows.append(ev)

json.dump(rows, open(os.path.join(out, "events.json"), "w"), indent=1)

# ---------------- markdown ----------------
def flag(b, t):
    return t if b else ""

groups = {}
for ev in rows:
    n = ev["event"]
    g = ("client" if n.startswith("net/minecraftforge/client/") else
         "fml.client" if n.startswith("net/minecraftforge/fml/client/") else
         "fml.common.gameevent" if "/gameevent/" in n else
         "fml.common.network" if "/fml/common/network" in n else
         "terraingen" if "/terraingen/" in n else
         "entity" if "/event/entity/" in n else
         "world" if "/event/world/" in n else
         "fluids/oredict/misc" if ("/fluids/" in n or "/oredict/" in n or "/common/Forge" in n) else
         "other")
    groups.setdefault(g, []).append(ev)

L = []
L.append("# Forge 1.8.9 event catalogue\n")
L.append("Generated by `tools/forgespec` (bytecode scan of forge-1.8.9-11.15.1.2318 universal jar, remapped notch -> SRG/MCP; patch scan of the Forge `1.8.9` branch) plus hand-curated notes in `tools/forgespec/curated_events.py`. Machine-readable form: `events.json`.\n")
L.append("Columns: **C** = `@Cancelable` (own or inherited; `post()` returns true if cancelled), **R** = `@HasResult`, **Side** = logical side(s) the post executes on, **MP** = needed by a multiplayer-only client (`yes`, `partial`, `no` = server/singleplayer only, listed but out of scope). **Fired at** gives `Forge-class.method` (compiled-line in `src/main/java/...`) and, for vanilla-triggered hooks, the vanilla caller (MCP names) and the Forge patch hunk (`patches/minecraft/...patch:line`).\n")
L.append("Buses: `MinecraftForge.EVENT_BUS` (all `net.minecraftforge.*` events, plus `FMLNetworkEvent`, `ConfigChangedEvent`, `FMLNetworkEvent`), `FMLCommonHandler.instance().bus()` (`TickEvent.*`, `InputEvent.*`, `gameevent.PlayerEvent.*`), `MinecraftForge.TERRAIN_GEN_BUS` and `MinecraftForge.ORE_GEN_BUS` (terrain/ore generation; all server-only).\n")
L.append("Inheritance: a listener for an event class also receives subclass events; per priority, listeners of the most-derived class run before listeners of its parent classes (ListenerList.java:160-170). `Cancelable`/`HasResult` are inherited through the generated `isCancelable()`/`hasResult()` overrides (EventSubscriptionTransformer.java:101-160).\n")
total = len(rows)
L.append("Totals: %d event classes (%d with an identifiable construct site), %d cancelable, %d with result.\n" % (
    total, sum(1 for e in rows if e["sites"]), sum(1 for e in rows if e["cancelable"]), sum(1 for e in rows if e["hasResult"])))
order = ["client", "fml.client", "fml.common.gameevent", "fml.common.network", "entity", "world", "terraingen", "fluids/oredict/misc", "other"]
for g in order:
    evs = groups.get(g)
    if not evs:
        continue
    L.append("\n## %s\n" % g)
    L.append("| ID | Event | C | R | Bus | Side | MP | Fired at |")
    L.append("|---|---|---|---|---|---|---|---|")
    for ev in evs:
        name = ev["event"].replace("net/minecraftforge/", "").replace("/", ".")
        eid = "EV-" + re.sub(r"[^A-Za-z0-9]+", "-", name).strip("-")
        sites = []
        for s in ev["sites"][:3]:
            cs = ", ".join(sorted({simple(c["class"]) + "." + c["mcp"] for c in s["vanillaCallers"]}))[:140]
            ref = ""
            if s["patchRefs"]:
                r = s["patchRefs"][0]
                ref = " [%s:%d]" % (r["patch"].replace("patches/minecraft/net/minecraft/", ""), r["patchLine"])
            sites.append("`%s.%s`(%s:%d)%s%s" % (simple(s["class"]), s["mcp"], os.path.basename(s["file"]).replace(".patch", ""), s["line"], (" from " + cs) if cs else "", ref))
        if len(ev["sites"]) > 3:
            sites.append("+%d more" % (len(ev["sites"]) - 3))
        fired = "<br>".join(sites) if sites else ("abstract base" if ev["abstract"] or not ev["constructors"] else "no static construct site (see notes)")
        bus = "/".join(b.replace("MinecraftForge.", "") for b in ev["bus"]) or "-"
        L.append("| %s | `%s` | %s | %s | %s | %s | %s | %s |" % (eid, name, "C" if ev["cancelable"] else "", "R" if ev["hasResult"] else "", bus, ev["side"], ev["mpClient"], fired))
    notes = [e for e in evs if any(k in e for k in ("when", "ordering", "thread", "notes"))]
    if notes:
        L.append("\n### Notes (%s)\n" % g)
        for ev in notes:
            name = ev["event"].replace("net/minecraftforge/", "").replace("/", ".")
            parts = []
            for k, lbl in (("thread", "thread"), ("when", "when"), ("ordering", "ordering"), ("phase", "phase"), ("notes", "notes")):
                if k in ev:
                    parts.append("%s: %s" % (lbl, ev[k]))
            L.append("- `%s` -- %s" % (name, "; ".join(parts)))
open(os.path.join(out, "events.md"), "w").write("\n".join(L) + "\n")
print("wrote", total, "events")
